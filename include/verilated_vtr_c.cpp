void VerilatedVtr::runDumpCallback(dumpCb_t cb, void* userp, Buffer* bufp) {
    if (!bufp->m_producer) {
        cb(userp, bufp);
        return;
    }
    auto& owner = bufp->m_owner;
    const bool mainThread = std::this_thread::get_id() == owner.m_dumpThread;
    try {
        if (!bufp->m_error) {
            bufp->m_vtr.use_producer(*bufp->m_producer);
            cb(userp, bufp);
        }
    } catch (...) { bufp->m_error = std::current_exception(); }
    bufp->m_vtr.release_producer();
    if (mainThread) {
        try {
            owner.m_vtr->use_producer(*owner.m_producer);
        } catch (...) { bufp->m_error = std::current_exception(); }
    }
}

